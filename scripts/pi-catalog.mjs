#!/usr/bin/env node
/**
 * Writes packages/shared/src/pi-catalog.ts from pi-ai's built-in model catalog
 * (the version apps/agent pins): each Anthropic, OpenAI and Google model's
 * context window and API prices. The shared package uses it where the vendor's
 * own model list says nothing, in the agent and in both clients alike, without
 * either loading pi-ai. Run it after bumping pi-ai:
 *
 *   node scripts/pi-catalog.mjs
 *
 * apps/agent/test/pi-catalog.test.ts fails while the file is out of date.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "packages", "shared", "src", "pi-catalog.ts");

export const PROVIDERS = ["anthropic", "openai", "google"];

/** The catalog's entries, by lowercase model id; the first provider to list an id keeps it. */
export async function catalog() {
  const { getBuiltinModels } = await import("@earendil-works/pi-ai/providers/all");
  const entries = {};
  for (const provider of PROVIDERS) {
    for (const m of getBuiltinModels(provider)) {
      const id = String(m.id).toLowerCase();
      if (entries[id] || !(m.contextWindow > 0)) continue;
      const c = m.cost ?? {};
      entries[id] = { window: m.contextWindow, input: c.input ?? 0, output: c.output ?? 0, cacheRead: c.cacheRead ?? 0, cacheWrite: c.cacheWrite ?? 0 };
    }
  }
  return Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
}

/** The file's text for these entries. */
export function render(entries, version) {
  const lines = Object.entries(entries).map(([id, e]) => `  ${JSON.stringify(id)}: { window: ${e.window}, input: ${e.input}, output: ${e.output}, cacheRead: ${e.cacheRead}, cacheWrite: ${e.cacheWrite} },`);
  return [
    "/**",
    ` * pi-ai ${version}'s built-in catalog of Anthropic, OpenAI and Google models: each one's`,
    " * context window in tokens and API prices in US dollars per million tokens",
    " * (cacheWrite 0: the vendor charges cache writes as input). Generated by",
    " * scripts/pi-catalog.mjs; do not edit by hand.",
    " */",
    "export interface CatalogModel {",
    "  window: number;",
    "  input: number;",
    "  output: number;",
    "  cacheRead: number;",
    "  cacheWrite: number;",
    "}",
    "",
    "export const PI_CATALOG: Readonly<Record<string, CatalogModel>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

export function piAiVersion() {
  return JSON.parse(fs.readFileSync(path.join(root, "apps", "agent", "package.json"), "utf-8")).dependencies["@earendil-works/pi-ai"];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(await catalog(), piAiVersion());
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(root, out)} (${Object.keys(await catalog()).length} models)`);
}
